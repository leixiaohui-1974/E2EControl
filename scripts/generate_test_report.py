def generate_detailed_report(run_result: dict, output_dir: Path) -> Path:
    """基于 HydroClaw MDReporter 生成详细测试报告。"""

    reporter = MDReporter()
    output_dir.mkdir(parents=True, exist_ok=True)

    # --- 构建 Markdown ---
    lines = []
    lines.append(f"# HydroE2E 测试报告: {Path(run_result['module']).stem}")
    lines.append("")

    # 概览卡片
    total = run_result["total"]
    passed = run_result["passed"]
    failed = run_result["failed"]
    errors = run_result["errors"]
    duration = run_result["duration"]
    pass_rate = (passed / total * 100) if total > 0 else 0

    lines.append("## 执行概览")
    lines.append("")
    lines.append(f"| 指标 | 值 |")
    lines.append(f"|------|-----|")
    lines.append(f"| **测试模块** | `{run_result['module']}` |")
    lines.append(f"| **执行时间** | {run_result['timestamp']} |")
    lines.append(f"| **总耗时** | {duration:.2f}s |")
    lines.append(f"| **测试总数** | {total} |")
    lines.append(f"| ✅ 通过 | {passed} ({pass_rate:.1f}%) |")
    lines.append(f"| ❌ 失败 | {failed} |")
    lines.append(f"| 💥 错误 | {errors} |")
    lines.append(f"| **通过率** | **{pass_rate:.1f}%** |")
    lines.append("")

    # 按测试类分组详情
    lines.append("## 详细结果")
    lines.append("")

    for cls_name, tests in run_result["class_results"].items():
        cls_passed = sum(1 for t in tests if t["status"] == "PASSED")
        cls_total = len(tests)
        cls_duration = sum(t["duration"] for t in tests)

        lines.append(f"### {cls_name}")
        lines.append(f"")
        lines.append(f"> {cls_passed}/{cls_total} 通过 · 耗时 {cls_duration:.3f}s")
        lines.append(f"")
        lines.append(f"| 状态 | 测试用例 | 说明 | 耗时 |")
        lines.append(f"|:----:|----------|------|-----:|")

        for t in tests:
            icon = "✅" if t["status"] == "PASSED" else ("❌" if t["status"] == "FAILED" else "💥")
            name = t["name"].replace("|", "\\|")
            doc = (t["doc"] or "-").replace("|", "\\|")
            lines.append(f"| {icon} | `{name}` | {doc} | {t['duration']*1000:.1f}ms |")

        lines.append("")

    # 失败详情
    failed_tests = [t for t in run_result["all_tests"] if t["status"] != "PASSED"]
    if failed_tests:
        lines.append("## 失败详情")
        lines.append("")
        for t in failed_tests:
            lines.append(f"### ❌ {t['name']}")
            lines.append(f"```")
            lines.append(t["error"] or "No error message")
            lines.append(f"```")
            lines.append("")

    # 性能分析
    lines.append("## 性能分析")
    lines.append("")

    all_tests = run_result["all_tests"]
    if all_tests:
        durations = [t["duration"] for t in all_tests]
        avg_duration = sum(durations) / len(durations)
        max_test = max(all_tests, key=lambda t: t["duration"])
        min_test = min(all_tests, key=lambda t: t["duration"])

        lines.append(f"| 指标 | 值 |")
        lines.append(f"|------|-----|")
        lines.append(f"| 平均耗时 | {avg_duration*1000:.1f}ms |")
        lines.append(f"| 最慢用例 | `{max_test['name']}` ({max_test['duration']*1000:.1f}ms) |")
        lines.append(f"| 最快用例 | `{min_test['name']}` ({min_test['duration']*1000:.1f}ms) |")
        lines.append(f"| 总吞吐量 | {total/duration:.1f} tests/s |")
        lines.append("")

        # Top 5 最慢
        lines.append("### 耗时 Top 5")
        lines.append("")
        lines.append("| 排名 | 测试用例 | 耗时 |")
        lines.append("|:----:|----------|-----:|")
        sorted_tests = sorted(all_tests, key=lambda t: t["duration"], reverse=True)
        for i, t in enumerate(sorted_tests[:5], 1):
            lines.append(f"| {i} | `{t['name']}` | {t['duration']*1000:.1f}ms |")
        lines.append("")

    # 测试覆盖的模块
    lines.append("## 覆盖模块")
    lines.append("")
    lines.append("本测试文件覆盖以下 HydroE2E 核心模块：")
    lines.append("")

    # 从测试类名推断覆盖模块
    module_map = {
        "TestSemanticInterpreter": ("hydroe2e.brain", "语义指令解析器"),
        "TestCanalPoolSimulator": ("hydroe2e.physics", "渠池水力学仿真"),
        "TestUniversalMPCSolver": ("hydroe2e.control", "MPC最优控制求解器"),
        "TestConfigManager": ("hydroe2e.config_manager", "YAML配置管理"),
        "TestSimulationDatabase": ("hydroe2e.database", "SQLite数据持久化"),
        "TestSimulationManager": ("hydroe2e.simulation_manager", "仿真编排器"),
        "TestExceptions": ("hydroe2e.exceptions", "自定义异常体系"),
        "TestMonitoringSystem": ("hydroe2e.monitor", "实时监控告警"),
    }

    lines.append("| 测试类 | 覆盖模块 | 功能 |")
    lines.append("|--------|----------|------|")
    for cls_name in run_result["class_results"]:
        if cls_name in module_map:
            mod, desc = module_map[cls_name]
            lines.append(f"| {cls_name} | `{mod}` | {desc} |")
        else:
            lines.append(f"| {cls_name} | - | - |")
    lines.append("")

    # 建议
    lines.append("## 改进建议")
    lines.append("")
    if pass_rate == 100:
        lines.append("- ✅ 所有测试通过，核心模块运行正常")
        lines.append("- 建议增加边界条件测试（极端水位、零流量）")
        lines.append("- 建议增加并发访问测试（数据库模块）")
        lines.append("- 建议添加性能基准回归测试")
    else:
        lines.append(f"- ⚠️ {failed + errors} 个测试未通过，请优先修复")
        lines.append("- 查看上方失败详情获取错误信息")
    lines.append("")

    # 写入 MD
    md_content = "\n".join(lines)
    md_path = output_dir / f"{Path(run_result['module']).stem}_report.md"
    md_path.write_text(md_content, encoding="utf-8")

    # 转 HTML
    html_body = markdown.markdown(
        md_content,
        extensions=["tables", "fenced_code", "codehilite"],
    )
    html_content = HTML_TEMPLATE.format(
        title=f"HydroE2E 测试报告 - {Path(run_result['module']).stem}",
        body=html_body,
        timestamp=run_result["timestamp"],
    )
    html_path = output_dir / f"{Path(run_result['module']).stem}_report.html"
    html_path.write_text(html_content, encoding="utf-8")

    print(f"✅ MD 报告:   {md_path}")
    print(f"✅ HTML 报告: {html_path}")

    return html_path


