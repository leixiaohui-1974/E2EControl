# ---------------------------------------------------------------------------
# 测试执行器
# ---------------------------------------------------------------------------

class DetailedTestRunner:
    """运行测试并收集详细结果。"""

    def __init__(self, test_module_path: str):
        self.test_module = test_module_path
        self.results: List[Dict[str, Any]] = []

    def run(self) -> Dict[str, Any]:
        """运行测试模块，返回结构化结果。"""
        loader = unittest.TestLoader()

        # 发现测试
        suite = loader.discover(
            start_dir=str(Path(self.test_module).parent),
            pattern=Path(self.test_module).name,
        )

        total_start = time.time()
        class_results = {}

        for test_group in suite:
            for test_case in test_group:
                if hasattr(test_case, '__iter__'):
                    for t in test_case:
                        self._run_single(t, class_results)
                else:
                    self._run_single(test_case, class_results)

        total_duration = time.time() - total_start

        # 汇总
        all_tests = []
        for cls_name, tests in class_results.items():
            all_tests.extend(tests)

        passed = sum(1 for t in all_tests if t["status"] == "PASSED")
        failed = sum(1 for t in all_tests if t["status"] == "FAILED")
        errors = sum(1 for t in all_tests if t["status"] == "ERROR")

        return {
            "module": self.test_module,
            "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "duration": total_duration,
            "total": len(all_tests),
            "passed": passed,
            "failed": failed,
            "errors": errors,
            "class_results": class_results,
            "all_tests": all_tests,
        }

    def _run_single(self, test, class_results: dict):
        cls_name = test.__class__.__name__
        test_name = str(test).split()[0]
        doc = test.shortDescription() or ""

        if cls_name not in class_results:
            class_results[cls_name] = []

        start = time.time()
        result = unittest.TestResult()
        test.run(result)
        duration = time.time() - start

        if result.wasSuccessful():
            status = "PASSED"
            error_msg = None
        elif result.failures:
            status = "FAILED"
            error_msg = result.failures[0][1]
        elif result.errors:
            status = "ERROR"
            error_msg = result.errors[0][1]
        else:
            status = "FAILED"
            error_msg = "Unknown failure"

        class_results[cls_name].append({
            "name": test_name,
            "class": cls_name,
            "doc": doc,
            "status": status,
            "duration": duration,
            "error": error_msg,
        })


